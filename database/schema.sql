-- ==============================================================================
-- FinGraph Database Schema: Core Entities & Indexes
-- Target Database: PostgreSQL 14+
-- Description: Core schema for graph-based money laundering detection system
-- ==============================================================================

-- Enable UUID extension if not already present
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- Utility function for automatically updating timestamp columns
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ------------------------------------------------------------------------------
-- 1. CUSTOMERS
-- Master table for individuals and corporate entities
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS customers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE customers IS 'Master record of individual and entity customers under financial monitoring';
COMMENT ON COLUMN customers.email IS 'Optional customer email address, uniquely constrained when present';

-- ------------------------------------------------------------------------------
-- 2. ACCOUNTS
-- Financial accounts held by customers
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS accounts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    account_number VARCHAR(64) NOT NULL UNIQUE,
    account_type VARCHAR(50) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_account_status CHECK (status IN ('ACTIVE', 'FROZEN', 'DORMANT', 'CLOSED', 'UNDER_REVIEW'))
);

COMMENT ON TABLE accounts IS 'Financial accounts owned by customers through which funds flow';
COMMENT ON COLUMN accounts.currency IS 'ISO 4217 currency code, defaults to INR';

-- ------------------------------------------------------------------------------
-- 3. TRANSACTIONS
-- Ledger of fund movements between accounts
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS transactions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    source_account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    destination_account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    amount NUMERIC(16, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    transaction_type VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'COMPLETED',
    description TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_transaction_positive_amount CHECK (amount > 0),
    CONSTRAINT chk_transaction_distinct_accounts CHECK (source_account_id <> destination_account_id),
    CONSTRAINT chk_transaction_status CHECK (status IN ('COMPLETED', 'PENDING', 'FLAGGED', 'REJECTED', 'CANCELLED', 'FAILED'))
);

COMMENT ON TABLE transactions IS 'Direct financial transfers between accounts inspected for AML patterns';
COMMENT ON COLUMN transactions.amount IS 'Monetary transfer amount, constrained to strictly positive values';

-- ------------------------------------------------------------------------------
-- 4. ALERTS
-- Suspicious activity alerts generated by analytical rules or graph traversals
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS alerts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    transaction_id UUID REFERENCES transactions(id) ON DELETE SET NULL,
    alert_type VARCHAR(100) NOT NULL,
    risk_score INTEGER NOT NULL,
    severity VARCHAR(20) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'NEW',
    title VARCHAR(255) NOT NULL,
    description TEXT,
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_alert_risk_score CHECK (risk_score >= 0 AND risk_score <= 100),
    CONSTRAINT chk_alert_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT chk_alert_status CHECK (status IN ('NEW', 'INVESTIGATING', 'ESCALATED', 'CLOSED_RESOLVED', 'CLOSED_FALSE_POSITIVE'))
);

COMMENT ON TABLE alerts IS 'Potential money laundering indicators and suspicious transaction reports';
COMMENT ON COLUMN alerts.evidence IS 'JSON structured evidence payload containing graph ring paths or transaction chains';

-- Trigger for alerts.updated_at
CREATE OR REPLACE TRIGGER trg_alerts_updated_at
BEFORE UPDATE ON alerts
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ------------------------------------------------------------------------------
-- 5. DETECTION RULES
-- Configurable rules and thresholds for AML risk evaluation
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS detection_rules (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT,
    enabled BOOLEAN NOT NULL DEFAULT true,
    thresholds JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE detection_rules IS 'AML pattern detection rule definitions and parameter thresholds';

-- Trigger for detection_rules.updated_at
CREATE OR REPLACE TRIGGER trg_detection_rules_updated_at
BEFORE UPDATE ON detection_rules
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ------------------------------------------------------------------------------
-- INDEXES
-- Optimized for high-throughput lookup, graph-edge extraction & alert dashboards
-- ------------------------------------------------------------------------------

-- Customer & Account relationships
CREATE INDEX IF NOT EXISTS idx_accounts_customer_id ON accounts(customer_id);
CREATE INDEX IF NOT EXISTS idx_accounts_status ON accounts(status);

-- Transaction lookups and chronological filtering
CREATE INDEX IF NOT EXISTS idx_transactions_source_account ON transactions(source_account_id);
CREATE INDEX IF NOT EXISTS idx_transactions_dest_account ON transactions(destination_account_id);
CREATE INDEX IF NOT EXISTS idx_transactions_occurred_at ON transactions(occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_transactions_created_at ON transactions(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_transactions_status ON transactions(status);
CREATE INDEX IF NOT EXISTS idx_transactions_type ON transactions(transaction_type);

-- Alert triage indexes
CREATE INDEX IF NOT EXISTS idx_alerts_transaction_id ON alerts(transaction_id);
CREATE INDEX IF NOT EXISTS idx_alerts_status ON alerts(status);
CREATE INDEX IF NOT EXISTS idx_alerts_severity ON alerts(severity);
CREATE INDEX IF NOT EXISTS idx_alerts_risk_score ON alerts(risk_score DESC);
CREATE INDEX IF NOT EXISTS idx_alerts_created_at ON alerts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_alerts_alert_type ON alerts(alert_type);
CREATE INDEX IF NOT EXISTS idx_alerts_status_risk ON alerts(status, risk_score DESC);

-- Detection rules indexes
CREATE INDEX IF NOT EXISTS idx_detection_rules_enabled ON detection_rules(enabled);
